use std::fs;
use std::path::PathBuf;

fn main() {
    let manifest_dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let ops_dir = manifest_dir.join("src/ops");
    let out_dir = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR"));
    let out_file = out_dir.join("registry_generated.rs");

    let mut slugs = Vec::new();
    if let Ok(entries) = fs::read_dir(&ops_dir) {
        for entry in entries.flatten() {
            if !entry.file_type().map(|t| t.is_dir()).unwrap_or(false) {
                continue;
            }
            let slug = entry.file_name().to_string_lossy().into_owned();
            if slug == "shared" {
                continue;
            }
            if entry.path().join("mod.rs").is_file() {
                slugs.push(slug);
            }
        }
    }
    slugs.sort();

    let mut body = String::from("// @generated by build.rs — do not edit.\n\n");
    for slug in &slugs {
        let vis = if slug.as_str() == "constant" { "pub " } else { "" };
        let mod_path = ops_dir.join(slug).join("mod.rs");
        let mod_path = mod_path.to_string_lossy().replace('\\', "/");
        body.push_str(&format!("#[path = \"{mod_path}\"]\n{vis}mod {slug};\n"));
    }
    body.push_str("\npub fn folder_specs() -> Vec<TopSpec> {\n    vec![\n");
    for slug in &slugs {
        match slug.as_str() {
            "syphon_in" | "syphon_out" => {
                body.push_str("#[cfg(target_os = \"macos\")]\n");
            }
            "spout_in" | "spout_out" => {
                body.push_str("#[cfg(target_os = \"windows\")]\n");
            }
            _ => {}
        }
        body.push_str(&format!("        {slug}::spec(),\n"));
    }
    body.push_str("    ]\n}\n");

    fs::write(&out_file, body).expect("write registry_generated.rs");

    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed={}", ops_dir.display());
    for slug in &slugs {
        println!(
            "cargo:rerun-if-changed={}",
            ops_dir.join(slug).join("mod.rs").display()
        );
    }
}